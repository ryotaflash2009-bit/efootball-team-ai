-- ============================================================================
-- rls_probe_records のロールバック(検証専用テーブルの安全な削除)
-- ============================================================================
--
-- 用途: RLS技術検証(PoC)が終わり、rls_probe_recordsが不要になった場合に、
--   このテーブル・トリガー関数・ポリシー・データをまとめて削除する。
--
-- 影響範囲: public.rls_probe_records とその付随オブジェクトだけ。
--   auth.users・他のSupabase Authテーブル・Supabaseのシステムスキーマは
--   一切変更しない。My Team等の本番データテーブルはそもそも作成していないため
--   影響しない。
--
-- 注意: DROP TABLE はテーブル内の全データ・ポリシー・トリガーを削除する
--   (この操作自体は取り消せない)。実行前に、本当に不要になったことを
--   確認すること。
-- ============================================================================

drop table if exists public.rls_probe_records;

-- テーブルに紐づくトリガーはテーブル削除時に自動的に削除されるが、
-- トリガー関数自体はスキーマ直下の独立オブジェクトのため明示的に削除する。
drop function if exists public.rls_probe_records_guard();

-- pgcrypto拡張(gen_random_uuid()用)は、他の用途でも使われている可能性があるため
-- ここでは削除しない(拡張の削除は影響範囲が広く、このロールバックの対象外)。
