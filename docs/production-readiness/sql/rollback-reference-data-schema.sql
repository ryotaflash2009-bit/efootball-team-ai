-- ============================================================================
-- reference_data スキーマのロールバック(参照データ検証環境の安全な削除)
-- ============================================================================
--
-- 用途: reference_dataスキーマ(選手カード・監督・分析補助データ)が不要に
--   なった場合、または投入し直す前にまっさらな状態へ戻したい場合に、
--   スキーマごと・関連オブジェクトをまとめて削除する。
--
-- 影響範囲: reference_data スキーマとその内部オブジェクトだけ。
--   public.my_team_snapshots・public.rls_probe_records・auth.users・
--   他のSupabaseシステムスキーマ・他の既存テーブルは一切変更しない。
--
-- 注意: DROP SCHEMA ... CASCADE は、reference_data配下の全テーブル・
--   全データ(投入済みの選手カード・監督・分析補助データ、投入バッチ履歴を
--   含む)・トリガー・関数・ポリシーを削除する(この操作自体は取り消せない)。
--   ローカルのSQLite(data/efootball.db)には一切影響しない
--   (この参照データは正本SQLiteから都度再投入できる設計のため)。
--
--   実行前に、本当に不要になったこと・再投入できる状態にあることを確認すること。
-- ============================================================================

drop schema if exists reference_data cascade;

