-- ============================================================================
-- my_team_snapshots のロールバック(検証専用テーブルの安全な削除)
-- ============================================================================
--
-- 用途: My Teamクラウド保存PoCが不要になった場合に、このテーブル・トリガー
--   関数・ポリシー・データをまとめて削除する。
--
-- 影響範囲: public.my_team_snapshots とその付随オブジェクトだけ。
--   auth.users・他のSupabase Authテーブル・Supabaseのシステムスキーマ・
--   他の既存テーブルは一切変更しない。
--
-- 注意: DROP TABLE はテーブル内の全データ(利用者がクラウドへ保存した
--   My Teamスナップショットを含む)・ポリシー・トリガーを削除する
--   (この操作自体は取り消せない)。ローカルのMy Team(localStorage)には
--   一切影響しない。実行前に、本当に不要になったことを確認すること。
-- ============================================================================

drop table if exists public.my_team_snapshots;

-- テーブルに紐づくトリガーはテーブル削除時に自動的に削除されるが、
-- トリガー関数自体はスキーマ直下の独立オブジェクトのため明示的に削除する。
drop function if exists public.my_team_snapshots_guard();

