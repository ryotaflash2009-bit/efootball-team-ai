/**
 * ブラックボックステストのレポート(Markdownテーブル)へ、任意の文字列を安全な1セルとして
 * 埋め込むための純関数。
 *
 * 対象文字がすべてエスケープされるよう、必ず`\`(Markdown自身のエスケープ文字)を先に
 * `\\`へエスケープし、その後で`|`(セル境界の区切り文字)を`\|`へエスケープする。
 * この順序を守らないと、値がもともと含んでいた`\`が、こちらが追加した`\|`のエスケープを
 * 無効化してしまい、`|`がテーブル区切りとして解釈されて表全体が崩れる
 * (CodeQL: incomplete string escaping — バックスラッシュ自体を未エスケープにしていた)。
 * 改行はテーブル行の境界を壊すため、そのまま出さずスペースへ置き換える。
 */
export function escapeMarkdownCell(value: string): string {
  return String(value)
    .replace(/\\/g, "\\\\")
    .replace(/\|/g, "\\|")
    .replace(/\r\n|\r|\n/g, " ");
}
